"""
Pydantic schemas and typed definitions for QuantLens-XAI Strategy Builder.
Strictly prevents arbitrary code injection and guarantees deterministic parsing.
"""

from typing import List, Optional, Dict, Any, Literal
from pydantic import BaseModel, Field, field_validator


class AssumedDefault(BaseModel):
    """Represents a strategy parameter assumed by default that is clearly labeled and user-editable."""
    parameter: str
    value: Any
    reason: str
    is_editable: bool = True


class IndicatorConfig(BaseModel):
    """Configuration for technical indicators used in the parsed strategy."""
    ema_fast_period: int = Field(default=10, ge=2, le=200, description="Fast EMA period")
    ema_slow_period: int = Field(default=30, ge=5, le=500, description="Slow EMA period")
    rsi_period: int = Field(default=14, ge=2, le=100, description="RSI calculation period")
    rsi_threshold: float = Field(default=65.0, ge=10.0, le=90.0, description="RSI upper boundary for entries")

    @field_validator("ema_slow_period")
    @classmethod
    def validate_ema_periods(cls, v, info):
        fast = info.data.get("ema_fast_period", 10)
        if v <= fast:
            raise ValueError(f"Slow EMA ({v}) must be strictly greater than Fast EMA ({fast})")
        return v


class EntryRule(BaseModel):
    """Structured entry logic: e.g. Fast EMA crosses above Slow EMA with RSI confirmation."""
    primary_condition: str = Field(
        default="ema_fast crosses_above ema_slow",
        description="Core trend crossover rule"
    )
    filter_condition: str = Field(
        default="rsi < 65",
        description="Secondary momentum confirmation filter"
    )
    order_type: Literal["market", "limit"] = "market"
    direction: Literal["BUY", "SELL"] = "BUY"


class ExitRule(BaseModel):
    """Structured exit logic: reverse crossover, stop-loss, or take-profit."""
    reversal_condition: str = Field(
        default="ema_fast crosses_below ema_slow",
        description="Opposing trend crossover exit"
    )
    stop_loss_pct: float = Field(default=2.0, ge=0.1, le=25.0, description="Stop-loss percentage")
    take_profit_pct: float = Field(default=4.0, ge=0.1, le=50.0, description="Take-profit percentage")


class RiskManagement(BaseModel):
    """Strict risk boundaries and capital allocation rules."""
    initial_capital: float = Field(default=100000.0, ge=1000.0, description="Virtual initial capital in INR (₹)")
    max_position_allocation_pct: float = Field(
        default=10.0, ge=1.0, le=100.0, description="Maximum allocation per position as % of capital"
    )
    max_open_positions: int = Field(default=1, ge=1, le=10, description="Maximum concurrent positions")
    brokerage_fee_pct: float = Field(default=0.05, description="Estimated fee per trade (0.05%)")
    slippage_pct: float = Field(default=0.05, description="Estimated market slippage (0.05%)")
    trading_mode: Literal["paper"] = "paper"


class StrategyDefinition(BaseModel):
    """Complete, validated strategy specification compiled from Natural Language."""
    strategy_id: str = Field(description="Unique strategy identifier")
    strategy_name: str = Field(default="EMA-RSI Quantitative Trend Strategy")
    symbol: str = Field(default="RELIANCE", description="NSE Stock ticker (e.g. RELIANCE, TCS, INFY)")
    timeframe: Literal["daily", "hourly"] = "daily"
    indicators: IndicatorConfig = Field(default_factory=IndicatorConfig)
    entry_rule: EntryRule = Field(default_factory=EntryRule)
    exit_rule: ExitRule = Field(default_factory=ExitRule)
    risk_config: RiskManagement = Field(default_factory=RiskManagement)
    raw_prompt: str = Field(description="Original user natural language input")
    assumed_defaults: List[AssumedDefault] = Field(default_factory=list)


class DecisionTraceStep(BaseModel):
    """One discrete step in the visual decision process explaining how the strategy was interpreted."""
    step_number: int
    stage_name: str
    description: str
    status: Literal["completed", "in_progress", "warning", "error"] = "completed"
    details: str
    timestamp_offset_ms: int = 0


class AIAdvisory(BaseModel):
    """Actionable educational analysis and risk disclosures generated by the local AI."""
    summary: str
    indicator_rationale: str
    entry_exit_mechanics: str
    market_regime_risks: str
    false_crossover_risks: str
    slippage_and_cost_impact: str
    overfitting_caveat: str
    suggested_improvements: List[str]
    disclaimer: str = (
        "Educational Analysis Only: This analysis is generated by a local machine learning system "
        "for academic decision-support under BCSE418L. It is not financial advice."
    )


class StrategyParseResponse(BaseModel):
    """Full API payload returned to the frontend upon clicking Analyze Strategy."""
    success: bool = True
    llm_runtime: str = Field(description="Name and version of local LLM executing inference")
    execution_time_ms: float = Field(description="Inference latency in milliseconds")
    strategy: StrategyDefinition
    decision_trace: List[DecisionTraceStep]
    advisory: AIAdvisory
    validation_status: Literal["VALID", "WARNING", "INVALID"] = "VALID"
    validation_errors: List[str] = Field(default_factory=list)
